-- 城市表创建脚本
-- 设置默认起始索引为 1000

-- 创建序列，起始值为 1000
CREATE SEQUENCE IF NOT EXISTS ext_cities_id_seq
    START WITH 1000
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

-- 创建城市表
DROP TABLE IF EXISTS ext_cities;
CREATE TABLE IF NOT EXISTS ext_cities (
    id BIGINT PRIMARY KEY DEFAULT nextval('ext_cities_id_seq'),
    code VARCHAR(50) NOT NULL DEFAULT '',
    name VARCHAR(50) NOT NULL DEFAULT '',
    province_code VARCHAR(50) NOT NULL DEFAULT '',
    remark VARCHAR(255) NOT NULL DEFAULT '',
    status SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 创建索引
CREATE UNIQUE INDEX IF NOT EXISTS idx_ext_cities_code ON ext_cities(code);
CREATE INDEX IF NOT EXISTS idx_ext_cities_province_code ON ext_cities(province_code);

-- 创建注释
COMMENT ON TABLE ext_cities IS '城市表，存储系统中城市信息';
COMMENT ON COLUMN ext_cities.id IS '城市唯一标识符，自增主键，起始值为1000';
COMMENT ON COLUMN ext_cities.code IS '城市编码';
COMMENT ON COLUMN ext_cities.name IS '城市名称';
COMMENT ON COLUMN ext_cities.province_code IS '省份编码';
COMMENT ON COLUMN ext_cities.remark IS '城市备注';
COMMENT ON COLUMN ext_cities.status IS '城市状态：1-正常，2-禁用';
COMMENT ON COLUMN ext_cities.created_at IS '记录创建时间，自动设置为当前时间';
COMMENT ON COLUMN ext_cities.updated_at IS '记录更新时间，自动设置为当前时间';

-- 创建触发器，自动更新更新时间
CREATE TRIGGER update_ext_cities_updated_at
    BEFORE UPDATE ON ext_cities
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

